export type TableForm = 'up' | 'down' | 'same';

export interface TableRow {
  rank: number;
  form: TableForm;
  code: string;
  logo: string;
  p: number;
  w: number;
  d: number;
  l: number;
}

export function tablePoints(row: TableRow): number {
  return row.w * 3 + row.d;
}

